import pytest
import torch
from torch import nn

from rl_lab.optim import GroupedOptimizer, Muon, build_optimizer


@torch.no_grad()
def _reference_muon_step(grads, weights, momentum, variance, *, lr, momentum_coefficient,
                         beta, weight_decay, ns_steps=5):
    # Independent NorMuon reference: pinned modded-nanogpt record adapted to gpt-lab.
    # Commit 29aefcfde8ab13f8b53a0975b88544ccd0b3e15e, 2025-11-10_CautiousWD.
    # Copyright (c) 2024 Keller Jordan; MIT, see LICENSES/modded-nanogpt-MIT.txt.
    # float32, normalization 1.01, eager matmul, and effective decay lr * wd.
    momentum.lerp_(grads, 1 - momentum_coefficient)
    update = grads.lerp(momentum, momentum_coefficient)
    tall = update.shape[-2] > update.shape[-1]
    x = update.mT if tall else update
    x = (x / (x.norm(dim=(-2, -1), keepdim=True) * 1.01 + 1e-6)).contiguous()
    for a, b, c in (
        (8.156554524902461, -22.48329292557795, 15.878769915207462),
        (4.042929935166739, -2.808917465908714, .5000178451051316),
        (3.8916678022926607, -2.772484153217685, .5060648178503393),
        (3.285753657755655, -2.3681294933425376, .46449024233003106),
        (2.3465413258596377, -1.7097828382687081, .42323551169305323),
    )[:ns_steps]:
        gram = x @ x.mT
        polynomial = b * gram + c * (gram @ gram)
        x = torch.baddbmm(x, polynomial, x, beta=a)
    update = x.mT if tall else x
    red_dim = -1 if weights.shape[-2] >= weights.shape[-1] else -2
    norm = update.norm(dim=(-2, -1), keepdim=True)
    variance.lerp_(update.square().mean(dim=red_dim, keepdim=True), 1 - beta)
    update = update * variance.clamp_min(1e-10).rsqrt()
    update = update * (norm / update.norm(dim=(-2, -1), keepdim=True).clamp_min(1e-10))
    update = update + weight_decay * weights * ((update * weights) >= 0)
    weights.add_(update, alpha=-lr * max(1., weights.shape[-2] / weights.shape[-1]) ** .5)


def test_muon_matches_independent_modded_nanogpt_reference_across_steps():
    compiler_limit = torch.compiler.config.recompile_limit
    generator = torch.Generator().manual_seed(123)
    hparams = dict(lr=.02, momentum=.95, beta=.9, weight_decay=.1, ns_steps=5)
    parameters = [nn.Parameter(torch.randn(shape, generator=generator) * .02)
                  for shape in ((7, 3), (7, 3), (3, 7), (4, 4))]
    optimizer = Muon(parameters, **hparams)
    reference = []
    for p in parameters:
        rows, columns = p.shape
        variance = torch.zeros((1, rows, 1) if rows >= columns else (1, 1, columns))
        reference.append((p.detach().unsqueeze(0).clone(), torch.zeros_like(p).unsqueeze(0), variance))
    for _ in range(3):
        for p, (weight, momentum, variance) in zip(parameters, reference):
            p.grad = torch.randn(p.shape, generator=generator) * .01
            _reference_muon_step(p.grad.unsqueeze(0), weight, momentum, variance,
                           lr=hparams["lr"], momentum_coefficient=hparams["momentum"],
                           beta=hparams["beta"], weight_decay=hparams["weight_decay"],
                           ns_steps=hparams["ns_steps"])
        optimizer.step()
        assert torch.compiler.config.recompile_limit == compiler_limit
        for p, (weight, momentum, variance) in zip(parameters, reference):
            torch.testing.assert_close(p, weight[0], rtol=2e-5, atol=2e-7)
            state = optimizer.state[p]
            torch.testing.assert_close(state["momentum_buffer"], momentum[0], rtol=2e-5, atol=2e-7)
            torch.testing.assert_close(state["second_momentum_buffer"], variance[0],
                                       rtol=2e-5, atol=2e-7)


def test_muon_matches_gpt_lab_reference_for_mixed_shapes():
    # Frozen values generated by the pinned upstream kernel with its compile decorator.
    reference = json.loads((Path(__file__).parent / "fixtures" / "gpt_lab_muon.json").read_text())
    parameters = [nn.Parameter(torch.arange(shape[0] * shape[1], dtype=torch.float32).reshape(shape) / 10 - 0.2)
                  for shape in (case["shape"] for case in reference["cases"])]
    # A second matrix in the tall bucket verifies batching without shared state.
    parameters.append(nn.Parameter(parameters[0].detach().clone()))
    unused = nn.Parameter(torch.ones(3, 2))
    optimizer = Muon([*parameters, unused], **reference["hparams"])
    for multiplier in (1.0, -0.7):
        for parameter in parameters:
            parameter.grad = torch.linspace(-0.4, 0.6, steps=parameter.numel()).reshape(parameter.shape) * multiplier
        optimizer.step()
    for parameter, case in zip(parameters, [*reference["cases"], reference["cases"][0]]):
        torch.testing.assert_close(parameter, torch.tensor(case["weight"]), rtol=2e-6, atol=2e-7)
        state = optimizer.state[parameter]
        torch.testing.assert_close(state["momentum_buffer"], torch.tensor(case["momentum"]), rtol=2e-6, atol=2e-7)
        torch.testing.assert_close(state["second_momentum_buffer"], torch.tensor(case["second_momentum"]),
                                   rtol=2e-6, atol=2e-7)
    assert unused not in optimizer.state
    torch.testing.assert_close(unused, torch.ones_like(unused))
    assert (optimizer.state[parameters[0]]["momentum_buffer"].data_ptr()
            != optimizer.state[parameters[-1]]["momentum_buffer"].data_ptr())


def test_mixed_optimizer_checkpoint_continues_with_scheduled_group_lrs():
    torch.manual_seed(0)
    model = nn.Linear(3, 2)
    config = {"groups": [
        {"name": "matrix", "patterns": ["weight"], "optimizer": "muon", "hparams": {"lr": 0.02}},
        {"name": "bias", "patterns": ["bias"], "optimizer": "adamw", "hparams": {"lr": 1e-3}},
    ]}
    optimizer = build_optimizer(model, config, betas=(0.8, 0.96), eps=1e-8, fused=False)
    assert isinstance(optimizer, GroupedOptimizer)
    scheduler = torch.optim.lr_scheduler.LambdaLR(optimizer, lambda step: 0.5 ** step)

    def update(model, optimizer, scheduler):
        optimizer.zero_grad()
        model(torch.ones(2, 3)).square().sum().backward()
        optimizer.step()
        scheduler.step()

    update(model, optimizer, scheduler)
    assert [group["lr"] for group in optimizer.param_groups] == [0.01, 5e-4]
    checkpoint = io.BytesIO()
    torch.save({"model": model.state_dict(), "optimizer": optimizer.state_dict(),
                "scheduler": scheduler.state_dict()}, checkpoint)
    checkpoint.seek(0)
    saved = torch.load(checkpoint, weights_only=True)
    resumed_model = deepcopy(model)
    resumed_model.load_state_dict(saved["model"])
    resumed = build_optimizer(resumed_model, config, betas=(0.8, 0.96), eps=1e-8, fused=False)
    resumed_scheduler = torch.optim.lr_scheduler.LambdaLR(resumed, lambda step: 0.5 ** step)
    resumed.load_state_dict(saved["optimizer"])
    resumed_scheduler.load_state_dict(saved["scheduler"])

    update(model, optimizer, scheduler)
    update(resumed_model, resumed, resumed_scheduler)
    for parameter, resumed_parameter in zip(model.parameters(), resumed_model.parameters()):
        torch.testing.assert_close(parameter, resumed_parameter, rtol=0, atol=0)
        for key, value in optimizer.state[parameter].items():
            torch.testing.assert_close(value, resumed.state[resumed_parameter][key], rtol=0, atol=0)
    assert [group["lr"] for group in resumed.param_groups] == [0.005, 2.5e-4]


@pytest.mark.parametrize("invalid", [{"ns_steps": 6}, {"beta": 1.0}, {"momentum": -0.1}])
def test_muon_rejects_invalid_hparams(invalid):
    with pytest.raises(ValueError):
        Muon([nn.Parameter(torch.ones(2, 3))], **invalid)


def test_muon_rejects_nonmatrix_parameters():
    with pytest.raises(ValueError, match="2D parameters"):
        Muon([nn.Parameter(torch.ones(3))])
